_SRC_CALCULATOR = '''\
"""Calculator module — implements basic arithmetic with validation."""

from __future__ import annotations

from dataclasses import dataclass
from tracing import traces


@dataclass
class CalcResult:
    """Result of a calculation."""
    value: float
    operation: str
    valid: bool = True
    error: str = ""


class Calculator:
    """Simple calculator with traced operations."""

    @traces("LLR-0001")
    def add(self, a: float, b: float) -> CalcResult:
        """Add two numbers."""
        return CalcResult(value=a + b, operation="add")

    @traces("LLR-0001")
    def subtract(self, a: float, b: float) -> CalcResult:
        """Subtract b from a."""
        return CalcResult(value=a - b, operation="subtract")

    @traces("LLR-0002")
    def divide(self, a: float, b: float) -> CalcResult:
        """Divide a by b with validation."""
        if not self._is_valid_divisor(b):
            return CalcResult(value=0, operation="divide", valid=False,
                              error="division by zero")
        return CalcResult(value=a / b, operation="divide")

    @traces("LLR-0002")
    def _is_valid_divisor(self, b: float) -> bool:
        """Check if b is a valid divisor — supports divide()."""
        return b != 0.0

    @traces("LLR-0001", "LLR-0002")
    def _format_result(self, result: CalcResult) -> str:
        """Format result for display — general helper."""
        if not result.valid:
            return f"Error: {result.error}"
        return f"{result.operation}: {result.value}"
'''

_TEST_CALCULATOR = '''\
"""Tests for calculator module — verifies LLR-0001 and LLR-0002."""

from src.calculator import Calculator, CalcResult
from tracing import traces


class TestAddition:
    """Tests for addition operations (LLR-0001)."""

    @traces("LLR-0001", case="CASE_LLR-0001")
    def test_add_positive_numbers(self):
        """Verify addition of positive numbers."""
        calc = Calculator()
        result = calc.add(2.0, 3.0)
        assert result.value == 5.0, f"expected 5.0, got {result.value}"
        assert result.operation == "add"

    @traces("LLR-0001", case="CASE_LLR-0001")
    def test_add_negative_numbers(self):
        """Verify addition with negative numbers."""
        calc = Calculator()
        result = calc.add(-1.0, -2.0)
        assert result.value == -3.0, f"expected -3.0, got {result.value}"

    @traces("LLR-0001", case="CASE_LLR-0001")
    def test_subtract(self):
        """Verify subtraction."""
        calc = Calculator()
        result = calc.subtract(5.0, 3.0)
        assert result.value == 2.0, f"expected 2.0, got {result.value}"


class TestDivision:
    """Tests for division operations (LLR-0002)."""

    @traces("LLR-0002", case="CASE_LLR-0002")
    def test_divide_normal(self):
        """Verify normal division."""
        calc = Calculator()
        result = calc.divide(10.0, 2.0)
        assert result.value == 5.0, f"expected 5.0, got {result.value}"
        assert result.valid is True

    @traces("LLR-0002", case="CASE_LLR-0002")
    def test_divide_by_zero(self):
        """Verify division by zero returns error."""
        calc = Calculator()
        result = calc.divide(10.0, 0.0)
        assert result.valid is False
        assert "zero" in result.error
'''

_TRACING_INIT = '''\
"""FORGE tracing decorators — runtime-queryable requirement annotations."""

from .decorator import traces

__all__ = ["traces"]
'''

_TRACING_DECORATOR = '''\
"""Requirement traceability decorator."""

from __future__ import annotations
from typing import TypeVar, Callable

_F = TypeVar("_F", bound=Callable)


def traces(*llr_ids: str, case: str | list[str] | None = None) -> Callable[[_F], _F]:
    """Annotate a function with requirement trace IDs."""
    if case is None:
        case_list: list[str] = []
    elif isinstance(case, str):
        case_list = [case]
    else:
        case_list = list(case)

    def decorator(obj: _F) -> _F:
        obj._trace_llrs = list(llr_ids)
        obj._trace_cases = case_list
        return obj

    return decorator
'''


# ── Workspace builder ─────────────────────────────────────────────────────────

def _build_workspace(ws: Path) -> None:
    """Create a complete, buildable workspace."""
    # Source
    src = ws / "src"
    src.mkdir()
    (src / "__init__.py").write_text("")
    (src / "calculator.py").write_text(_SRC_CALCULATOR)

    # Tests
    tests = ws / "tests"
    tests.mkdir()
    (tests / "__init__.py").write_text("")
    (tests / "test_calculator.py").write_text(_TEST_CALCULATOR)

    # Tracing package
    tracing = ws / "tracing"
    tracing.mkdir()
    (tracing / "__init__.py").write_text(_TRACING_INIT)
    (tracing / "decorator.py").write_text(_TRACING_DECORATOR)

    # Bazel workspace (MODULE.bazel, BUILD files, etc)
    init_bazel_workspace(ws)


# ── Graph stub ────────────────────────────────────────────────────────────────


class _StubGraph:
    """Minimal stand-in for ProjectGraph — only implements all_nodes().

    Mirrors the calculator workspace: one DESIGN (→ src/calculator.py),
    two LLRs, and two CASE_LLR nodes (→ tests/test_calculator.py).
    """

    def __init__(self, nodes: list[GraphNode] | None = None) -> None:
        self._nodes = nodes if nodes is not None else _default_graph_nodes()

    def all_nodes(self) -> list[GraphNode]:
        return list(self._nodes)


def _stub_graph() -> ProjectGraph:
    """Return a `_StubGraph` typed as `ProjectGraph`.

    ``find_gaps`` only calls ``all_nodes()`` on the graph it is given, so the
    stub is substitutable at runtime; the cast records that for the checker.
    """
    return cast("ProjectGraph", _StubGraph())


def _default_graph_nodes() -> list[GraphNode]:
    """Graph nodes that match the calculator workspace layout."""
    return [
        GraphNode(
            node_id="DESIGN-calc",
            node_type="DESIGN",
            title="Calculator",
        ),
        GraphNode(node_id="LLR-0001", node_type="LLR", title="Arithmetic"),
        GraphNode(node_id="LLR-0002", node_type="LLR", title="Division"),
        GraphNode(
            node_id="CASE_LLR-0001",
            node_type="CASE_LLR",
            title="Calculator",
        ),
        GraphNode(
            node_id="CASE_LLR-0002",
            node_type="CASE_LLR",
            title="Calculator",
        ),
    ]



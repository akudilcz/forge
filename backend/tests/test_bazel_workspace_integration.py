def test_find_gaps_syntax_error_is_highest_file_priority(tmp_path: Path) -> None:
    """SYNTAX_ERROR gaps should sort before UNTRACED_FUNCTIONS gaps.

    The syntax error is in src/calculator.py (replaced entirely with broken
    code, so it has 0 parsed functions).  The untraced function is
    test_no_trace in tests/test_calculator.py (valid syntax, no @traces).
    """
    _build_workspace(tmp_path)

    # Source with syntax error — replaces entire file
    calc = tmp_path / "src" / "calculator.py"
    calc.write_text("def broken(\n")

    # Test with an untraced function (valid syntax)
    test_file = tmp_path / "tests" / "test_calculator.py"
    test_file.write_text(
        _TEST_CALCULATOR + "\n\ndef test_no_trace():\n    assert True\n"
    )

    source_files, test_files = scan_files(tmp_path)
    graph = _stub_graph()

    gaps = find_gaps(source_files, test_files, [], graph)

    # Verify both gap types are present and from the expected files
    syntax_gaps = [g for g in gaps if g.kind == GapKind.SYNTAX_ERROR]
    untraced_gaps = [g for g in gaps if g.kind == GapKind.UNTRACED_FUNCTIONS]
    assert len(syntax_gaps) == 1
    assert syntax_gaps[0].file_path == "src/calculator.py"
    assert len(untraced_gaps) == 1
    assert untraced_gaps[0].file_path == "tests/test_calculator.py"

    # SYNTAX_ERROR (priority 1) must sort before UNTRACED_FUNCTIONS (6)
    kinds = [g.kind for g in gaps]
    assert kinds.index(GapKind.SYNTAX_ERROR) < kinds.index(GapKind.UNTRACED_FUNCTIONS)



@pytest.mark.slow
@pytest.mark.skipif(not _has_bazel(), reason="bazel not available")
def test_bazel_test_passes(tmp_path: Path) -> None:
    """Full integration: bazel test //tests/... should pass."""
    _build_workspace(tmp_path)

    result = subprocess.run(
        ["bazel", "test", "//tests/...", "--test_output=errors"],
        cwd=str(tmp_path),
        capture_output=True,
        text=True,
        timeout=120,
    )

    assert result.returncode == 0, (
        f"bazel test failed:\nSTDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
    )

def _has_bazel() -> bool:
    """Return True if bazel is runnable.

    Evaluated at import time by the skipif below, so it must swallow
    FileNotFoundError rather than let it escape and break collection.
    """
    try:
        return subprocess.run(["bazel", "version"], capture_output=True, timeout=30).returncode == 0
    except (FileNotFoundError, subprocess.TimeoutExpired, OSError):
        return False



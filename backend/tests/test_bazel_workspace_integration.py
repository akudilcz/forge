    req_gaps = [g for g in gaps if g.kind == GapKind.UNCOVERED_REQUIREMENT]
    assert len(req_gaps) == 2, f"expected 2 UNCOVERED_REQUIREMENT gaps, got {len(req_gaps)}"
    req_ids = {g.node_id for g in req_gaps}
    assert req_ids == {"LLR-0001", "LLR-0002"}



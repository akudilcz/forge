async def _build_flow(
    integration_config: ForgeConfig, root: Path, *, name: str
) -> Any:
    workspace = root / "workspace"
    workspace.mkdir()
    config = integration_config.model_copy(deep=True)
    config.project.workspace_dir = str(workspace)
    config.project.name = name
    builder = ForgeBuilder(config=config, workspace=workspace, db_path=root / "forge.db")
    return await builder.build()


def _namelist(zip_path: Path) -> list[str]:
    assert zip_path.exists(), f"phase 14 produced no archive at {zip_path}"
    with zipfile.ZipFile(zip_path) as zf:
        assert zf.testzip() is None, "deliverables archive is corrupt"
        return zf.namelist()


def _read_member(zip_path: Path, name: str) -> str:
    with zipfile.ZipFile(zip_path) as zf:
        return zf.read(name).decode("utf-8")


def _status(flow: Any, phase: int) -> str:
    row = flow.phase_store.get(phase)
    assert row is not None, f"phase {phase} missing from the phase store"
    return str(row["status"])


# ── Happy path ───────────────────────────────────────────────────────────────


async def test_deliverables_zip_contains_source_and_rendered_docs(
    integration_config: ForgeConfig, tmp_path: Path
) -> None:
    flow = await _build_flow(integration_config, tmp_path, name="p14-happy")
    await _seed_graph(flow.graph)
    workspace = flow._workspace
    (workspace / SOURCE_FILE).write_text(SOURCE_CONTENT, encoding="utf-8")
    (workspace / TEST_FILE).write_text(TEST_CONTENT, encoding="utf-8")

    await flow.run_phase(14)

    assert _status(flow, 14) == "complete"
    names = _namelist(workspace / "deliverables.zip")

    assert "deliverables/README.md" in names, f"no README in bundle: {names[:15]}"
    for doc in DOC_NAMES:
        assert f"deliverables/docs/{doc}" in names, f"missing rendered doc: {doc}"
    assert f"deliverables/{SOURCE_FILE}" in names, "source file not bundled"
    assert f"deliverables/{TEST_FILE}" in names, "test file not bundled"

    # The bundled source must be the workspace file, byte for byte.
    bundled = _read_member(workspace / "deliverables.zip", f"deliverables/{SOURCE_FILE}")
    assert bundled == SOURCE_CONTENT


async def test_rendered_docs_carry_graph_content(
    integration_config: ForgeConfig, tmp_path: Path
) -> None:
    flow = await _build_flow(integration_config, tmp_path, name="p14-docs")
    await _seed_graph(flow.graph)
    workspace = flow._workspace
    (workspace / SOURCE_FILE).write_text(SOURCE_CONTENT, encoding="utf-8")
    (workspace / TEST_FILE).write_text(TEST_CONTENT, encoding="utf-8")

    await flow.run_phase(14)

    zip_path = workspace / "deliverables.zip"
    reqs = _read_member(zip_path, "deliverables/docs/01-Requirements-Specification.md")
    assert "HLR-0001" in reqs, "requirements doc must list the seeded HLR"
    assert "LLR-0001" in reqs, "requirements doc must list the seeded LLR"
    matrix = _read_member(zip_path, "deliverables/docs/06-Traceability-Matrix.md")
    assert "LLR-0001" in matrix, "traceability matrix must cross-reference the LLR"


async def test_rerun_produces_identical_archive_structure(
    integration_config: ForgeConfig, tmp_path: Path
) -> None:
    """Phase 14 is documented as deterministic: same graph → same output."""
    flow = await _build_flow(integration_config, tmp_path, name="p14-rerun")
    await _seed_graph(flow.graph)
    workspace = flow._workspace
    (workspace / SOURCE_FILE).write_text(SOURCE_CONTENT, encoding="utf-8")
    (workspace / TEST_FILE).write_text(TEST_CONTENT, encoding="utf-8")

    await flow.run_phase(14)
    first = _namelist(workspace / "deliverables.zip")

    await flow.run_phase(14)
    second = _namelist(workspace / "deliverables.zip")

    assert first == second, "re-running phase 14 changed the archive member list"
    assert _status(flow, 14) == "complete"


# ── Edge: empty workspace and empty graph ────────────────────────────────────


async def test_empty_workspace_completes_with_minimal_wellformed_bundle(
    integration_config: ForgeConfig, tmp_path: Path
) -> None:
    """No graph nodes, no generated files — still a well-formed bundle.

    design/24_phase_14_build_deliverables.md specifies deterministic
    packaging with no failure path, so the phase must complete and produce
    the doc skeleton rather than raising or emitting a corrupt archive.
    """
    flow = await _build_flow(integration_config, tmp_path, name="p14-empty")
    workspace = flow._workspace

    await flow.run_phase(14)

    assert _status(flow, 14) == "complete"
    names = _namelist(workspace / "deliverables.zip")
    assert "deliverables/README.md" in names
    for doc in DOC_NAMES:
        assert f"deliverables/docs/{doc}" in names, f"missing rendered doc: {doc}"
    # Nothing was generated, so nothing beyond README + docs may be bundled.
    extras = [
        n for n in names
        if not n.startswith("deliverables/docs/") and n != "deliverables/README.md"
    ]
    assert extras == [], f"empty build bundled unexpected files: {extras}"

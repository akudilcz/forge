"""Phase 14 (build deliverables) integration tests — deterministic, no LLM.

Seeds the full precondition graph plus generated source/test files in the
workspace, then runs ONLY phase 14 through the production flow and asserts:

  * ``deliverables.zip`` is produced with the documented structure —
    README, the seven rendered docs, and copies of source + test files
  * rendered docs actually carry the graph content (requirement IDs)
  * a re-run is deterministic (identical archive member list)
  * an empty workspace + empty graph still completes with a well-formed,
    minimal bundle (the design doc specifies deterministic packaging with
    no failure path — "given the same graph state, it always produces
    identical output")
"""

from __future__ import annotations


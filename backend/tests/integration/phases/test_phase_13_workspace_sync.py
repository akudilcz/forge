"""Phase 13 (workspace sync) integration tests — deterministic, no LLM.

Seeds the full precondition graph (PROJECT through DESIGN/SUITE/CASE, with
``file_path`` properties as phase 12 leaves them) plus real generated files
on disk, then runs ONLY phase 13 through the production flow and asserts:

  * CODE/TEST child nodes are created with content hashes and trace links
  * a DESIGN whose declared file is missing surfaces loudly — a MISSING_CODE
    sync gap plus an UNSYNCED_DESIGN structural gap — instead of failing
    silently or claiming completion
  * a re-run over unchanged content is a no-op (hash and version stable)
  * a changed file is refreshed in place, not duplicated
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

import pytest

from backend.analysis.gap_analyser import GapAnalyser
from backend.analysis.gaps import GapType
from backend.config.models import ForgeConfig
from backend.forge_builder import ForgeBuilder
from backend.graph.models import GraphNode, LifecycleState, NodeType

pytestmark = [pytest.mark.integration, pytest.mark.asyncio, pytest.mark.timeout(900)]

SOURCE_FILE = "src/arithmetic.py"
TEST_FILE = "tests/test_arithmetic.py"

SOURCE_CONTENT = '''"""Arithmetic module (as generated by phase 12)."""
from tracing import traces


@traces("LLR-0001")
def add(a: float, b: float) -> float:
    return a + b
'''

TEST_CONTENT = '''"""Tests for the arithmetic module (as generated by phase 12)."""
from tracing import traces

from src.arithmetic import add


@traces("LLR-0001", case="CASE_LLR-0001")
def test_add_returns_sum() -> None:
    assert add(2, 3) == 5
'''


def _sha256(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


# ── Seeding ──────────────────────────────────────────────────────────────────


